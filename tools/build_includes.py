#!/usr/bin/env python3
"""Generate the two animatable SVG includes from the brand SVGs.

  assets/img/mark.svg            -> _includes/lantern-mark.html
  assets/img/logo-horizontal.svg -> _includes/wordmark.html

The lantern is split so the flame tongue, the frame and each rot pixel can
move on their own. The wordmark is split so ROT can glitch in horizontal
bands while LANTERN and SOFTWARE stay put. The splitting depends on how the
brand SVGs are drawn, so any surprise stops the script instead of producing
a quietly wrong include.

Run it again whenever mark.svg or logo-horizontal.svg changes:
    python3 tools/build_includes.py
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GENERATED = "{{% comment %}}Generated by tools/build_includes.py from assets/img/{src}. Edit the script, not this file.{{% endcomment %}}\n"


def fail(message):
    sys.exit(f"build_includes: {message}")


def subpaths(d):
    return [s.strip() for s in re.split(r"(?=M)", d) if s.strip()]


def bbox(d):
    nums = [tuple(map(float, p)) for p in re.findall(r"(-?[\d.]+),(-?[\d.]+)", d)]
    if not nums:
        fail(f"no coordinates found in path data: {d[:60]!r}")
    xs, ys = [n[0] for n in nums], [n[1] for n in nums]
    return min(xs), min(ys), max(xs), max(ys)


def path_data(svg_text, expected, name):
    found = re.findall(r'd="([^"]+)"', svg_text)
    if len(found) != expected:
        fail(f"{name}: expected {expected} <path d=...> elements, found {len(found)}")
    return found


def lantern_mark(svg_text):
    amber_d, mint_d = path_data(svg_text, 2, "mark.svg")
    amber = subpaths(amber_d)  # [left pane, centre pane, flame outline, right pane, tongue]
    mint = subpaths(mint_d)    # frame pieces, then 8 square rot pixels (x >= 338)
    if len(amber) != 5:
        fail(f"mark.svg: expected 5 amber pieces, found {len(amber)}")
    frame_parts = [s for s in mint if bbox(s)[0] < 338]
    rot_parts = [s for s in mint if bbox(s)[0] >= 338]
    if len(rot_parts) != 8:
        fail(f"mark.svg: expected 8 rot pixels, found {len(rot_parts)}")
    if not frame_parts:
        fail("mark.svg: no frame pieces found")
    for s in rot_parts:
        x0, y0, x1, y1 = bbox(s)
        if (x1 - x0) > 40:
            fail(f"mark.svg: unexpected rot piece {s}")

    rot_rects = "".join(
        f'<rect class="rp" x="{x0:.0f}" y="{y0:.0f}" width="{x1-x0:.0f}" height="{y1-y0:.0f}"/>'
        for x0, y0, x1, y1 in map(bbox, rot_parts)
    )
    return f'''<svg class="mark" viewBox="0 0 480 760" role="img" aria-label="The Lantern Rot lantern">
  <path class="glass" fill-rule="evenodd" d="{amber[0]} {amber[1]} {amber[2]} {amber[3]}"/>
  <path class="tongue" d="{amber[4]}"/>
  <path class="frame" fill-rule="evenodd" d="{' '.join(frame_parts)}"/>
  <g class="rot-pixels">{rot_rects}</g>
</svg>
'''


def wordmark(svg_text):
    # logo-horizontal.svg draws 5 paths: two for the lantern icon, then the
    # three words. Only the words are used here.
    _, _, lantern_d, rot_d, software_d = path_data(svg_text, 5, "logo-horizontal.svg")
    boxes = [bbox(d) for d in (lantern_d, rot_d, software_d)]
    X0 = min(b[0] for b in boxes) - 4
    Y0 = min(b[1] for b in boxes) - 4
    X1 = max(b[2] for b in boxes) + 14
    Y1 = max(b[3] for b in boxes) + 4
    rx0, ry0, rx1, ry1 = bbox(rot_d)
    rh = ry1 - ry0
    if rh <= 0 or rx1 <= rx0:
        fail("logo-horizontal.svg: ROT has no area")
    band = lambda a, b: (ry0 + rh * a, rh * (b - a))
    b1y, b1h = band(0.30, 0.44)
    b2y, b2h = band(0.68, 0.80)
    return f'''<svg class="word" viewBox="{X0:.1f} {Y0:.1f} {X1-X0:.1f} {Y1-Y0:.1f}" role="img" aria-label="Lantern Rot Software">
  <defs>
    <clipPath id="band1"><rect x="{rx0-40:.1f}" y="{b1y:.1f}" width="{rx1-rx0+80:.1f}" height="{b1h:.1f}"/></clipPath>
    <clipPath id="band2"><rect x="{rx0-40:.1f}" y="{b2y:.1f}" width="{rx1-rx0+80:.1f}" height="{b2h:.1f}"/></clipPath>
    <clipPath id="notbands" clip-rule="evenodd"><path clip-rule="evenodd" d="M{rx0-40:.1f},{ry0-10:.1f} H{rx1+40:.1f} V{ry1+10:.1f} H{rx0-40:.1f} Z M{rx0-40:.1f},{b1y:.1f} V{b1y+b1h:.1f} H{rx1+40:.1f} V{b1y:.1f} Z M{rx0-40:.1f},{b2y:.1f} V{b2y+b2h:.1f} H{rx1+40:.1f} V{b2y:.1f} Z"/></clipPath>
    <path id="rotp" d="{rot_d}"/>
  </defs>
  <path class="w-lantern" d="{lantern_d}"/>
  <g class="w-rot">
    <use class="rot-base" href="#rotp"/>
    <g clip-path="url(#band1)"><use class="rot-slice s1" href="#rotp"/></g>
    <g clip-path="url(#band2)"><use class="rot-slice s2" href="#rotp"/></g>
  </g>
  <path class="w-software" d="{software_d}"/>
</svg>
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--img-dir", type=Path, default=ROOT / "assets/img", help="where mark.svg and logo-horizontal.svg live")
    parser.add_argument("--out-dir", type=Path, default=ROOT / "_includes", help="where the includes are written")
    args = parser.parse_args()

    jobs = [
        ("mark.svg", "lantern-mark.html", lantern_mark),
        ("logo-horizontal.svg", "wordmark.html", wordmark),
    ]
    # Build everything before writing anything, so a bad input leaves no half-update.
    built = []
    for src, out, build in jobs:
        path = args.img_dir / src
        if not path.exists():
            fail(f"missing {path}")
        built.append((args.out_dir / out, GENERATED.format(src=src) + build(path.read_text())))
    args.out_dir.mkdir(parents=True, exist_ok=True)
    for path, text in built:
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT) if path.is_relative_to(ROOT) else path} ({len(text)} bytes)")


if __name__ == "__main__":
    main()
