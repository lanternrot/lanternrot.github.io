#!/usr/bin/env python3
"""Build the hero parade: sprite images plus _data/parade.yml.

For each hero in PARADE it copies Dorf's 8-frame idle strip
(<dorf>/src/assets/heroes/sprites/<id>_idle.png) to assets/img/heroes/<id>.webp
(lossless), and records the hero's in-game display name in _data/parade.yml.

Names come from the hero data files (<dorf>/src/data/heroes/*star/<id>.js),
never from file names: several early heroes were renamed, so wandering_bard
is "Harl the Handsom" in the game.

Needs Pillow. Run it when the roster changes:
    python3 tools/build_parade.py
"""
import argparse
import json
import re
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent

# The 24 heroes in the parade, in belt order.
PARADE = ["sir_gallan", "swift_arrow", "apprentice_mage", "grandmother_rot", "knuckle_bess",
          "lady_moonwhisper", "bones_mccready", "margit", "inspector_grell", "street_busker",
          "aurora_the_dawn", "gravedigger_mott", "onibaba", "penny_dreadful", "torga_bloodbeat",
          "village_healer", "shinobi_jin", "soot_nan", "wandering_bard", "vespera",
          "ember_witch", "copper_jack", "sister_marrow", "rat_catcher"]

FRAMES = 8


def fail(message):
    sys.exit(f"build_parade: {message}")


def hero_name(hero_data, hero_id):
    """The in-game display name, read from the hero's data file."""
    files = list(hero_data.glob(f"*star/{hero_id}.js"))
    if len(files) != 1:
        fail(f"expected one data file for {hero_id}, found {files}")
    match = re.search(r"name:\s*(['\"])(.+?)\1", files[0].read_text())
    if not match:
        fail(f"no name in {files[0]}")
    return match.group(2)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--dorf", type=Path, default=Path.home() / "code/dorf", help="path to the Dorf repo")
    parser.add_argument("--img-out", type=Path, default=ROOT / "assets/img/heroes", help="where the .webp strips go")
    parser.add_argument("--data-out", type=Path, default=ROOT / "_data/parade.yml", help="where the roster YAML goes")
    args = parser.parse_args()

    sprites = args.dorf / "src/assets/heroes/sprites"
    hero_data = args.dorf / "src/data/heroes"

    # Check every hero before writing anything, so a bad input leaves no half-update.
    heroes = []
    for hero_id in PARADE:
        strip = sprites / f"{hero_id}_idle.png"
        if not strip.exists():
            fail(f"missing idle strip: {strip}")
        width, height = Image.open(strip).size
        if width != height * FRAMES:
            fail(f"{strip} is {width}x{height}, expected {FRAMES} square frames")
        heroes.append((hero_id, strip, hero_name(hero_data, hero_id)))

    args.img_out.mkdir(parents=True, exist_ok=True)
    args.data_out.parent.mkdir(parents=True, exist_ok=True)
    for hero_id, strip, _ in heroes:
        Image.open(strip).convert("RGBA").save(args.img_out / f"{hero_id}.webp", "WEBP", lossless=True, method=6)

    lines = ["# Generated by tools/build_parade.py. Names are read from Dorf's hero data files."]
    for hero_id, _, name in heroes:
        # JSON strings are valid YAML double-quoted scalars, so quoting and escaping are handled.
        lines.append(f"- id: {hero_id}\n  name: {json.dumps(name, ensure_ascii=False)}")
    args.data_out.write_text("\n".join(lines) + "\n")
    print(f"wrote {len(heroes)} heroes to {args.data_out} and {args.img_out}")


if __name__ == "__main__":
    main()
